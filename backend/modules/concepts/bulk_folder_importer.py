"""OpenMRS Bulk Folder Importer.

Recursively imports an entire folder tree generated by the DHIS2 metadata converter:
Walks post-order (bottom-up) so child section concepts and concept-sets are imported
before the parent stage-level sets that reference them.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Callable, Optional
import requests

from backend.modules.concepts.openmrs_importer import (
    OpenMRSClient,
    error_detail,
    CODED_DATATYPES,
    extract_concept_name,
)
from backend.core.config import settings


import zipfile

def resolve_concept_directory(target_path: str | Path) -> Path:
    """Intelligently resolve a target directory or uploaded archive containing concept folders.
    
    Handles:
    1. Direct existing directory paths (e.g. /data/exports/dhis2-concepts/Maternal Inpatient Data).
    2. Uploaded zip files (e.g. /data/uploads/FINC_concepts.zip) by auto-extracting.
    3. Common container aliases and missing parent folders (e.g. /data/exports/Maternal Inpatient Data -> /data/exports/dhis2-concepts/Maternal Inpatient Data).
    4. Simple folder names (e.g. 'Maternal Inpatient Data', 'FINC', 'NCF').
    5. Case-insensitive deep search across known storage locations (/data/output_concepts, /data/exports, /data/uploads).
    """
    if not target_path:
        raise ValueError("No directory path provided.")

    raw = str(target_path).strip().strip("'\"")
    if not raw:
        raise ValueError("Empty directory path provided.")

    p = Path(raw)

    # 1. Zip archive extraction
    if p.is_file() and p.suffix.lower() == ".zip":
        extract_dir = settings.uploads_dir / f"extracted_{p.stem}"
        extract_dir.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(p, "r") as z:
            z.extractall(extract_dir)
        children = [c for c in extract_dir.iterdir() if c.is_dir() and not c.name.startswith(".")]
        if len(children) == 1 and any(children[0].rglob("*.json")):
            return children[0]
        return extract_dir

    # 2. Direct directory match
    if p.is_dir():
        return p

    # 3. Check candidate base roots
    data_dir = Path(settings.DATA_DIR)
    roots = [
        data_dir / "output_concepts",
        data_dir / "exports" / "dhis2-concepts",
        data_dir / "exports",
        data_dir / "uploads",
        data_dir / "exports" / "Tests",
        Path("/data/output_concepts"),
        Path("/data/exports/dhis2-concepts"),
        Path("/data/exports"),
        Path("/data/uploads"),
        Path("/data/exports/Tests"),
    ]
    name_only = p.name

    for root in roots:
        cand_path = root / raw.lstrip("/")
        if cand_path.is_dir():
            return cand_path
        cand_name = root / name_only
        if cand_name.is_dir():
            return cand_name

    # 4. Deep search across roots for matching directory name
    for root in roots:
        if not root.is_dir():
            continue
        try:
            for cand in root.rglob("*"):
                if cand.is_dir() and cand.name.lower() == name_only.lower():
                    if any(cand.rglob("*.json")):
                        return cand
        except Exception:
            pass

    # 5. Check if a zip with this name exists in uploads or exports
    zip_roots = [data_dir / "exports", data_dir / "uploads", data_dir / "output_concepts", Path("/data/exports"), Path("/data/uploads"), Path("/data/output_concepts")]
    for root in zip_roots:
        if not root.is_dir():
            continue
        for zf in [root / f"{name_only}.zip", root / f"{p.stem}.zip"]:
            if zf.is_file():
                return resolve_concept_directory(zf)

    available = [d["path"] for d in get_available_concept_directories()]
    avail_str = "\n  - " + "\n  - ".join(available[:10]) if available else " (none found)"
    raise ValueError(
        f"Directory '{raw}' not found on server.\n"
        f"Detected available concept folders on server:{avail_str}"
    )


def get_available_concept_directories() -> list[dict]:
    """Scan and return a list of valid concept program directories on the server."""
    data_dir = Path(settings.DATA_DIR)
    candidates = [
        data_dir / "output_concepts",
        data_dir / "exports" / "dhis2-concepts",
        data_dir / "exports" / "Tests",
        data_dir / "exports",
        data_dir / "uploads",
        Path("/data/output_concepts"),
        Path("/data/exports/dhis2-concepts"),
        Path("/data/exports/Tests"),
        Path("/data/exports"),
        Path("/data/uploads"),
    ]
    discovered = []
    seen = set()
    for root in candidates:
        if not root.is_dir():
            continue
        try:
            entries = sorted(list(root.iterdir()), key=lambda p: p.name.lower())
        except Exception:
            entries = []
        for d in entries:
            if not d.is_dir() or d.name.startswith("."):
                continue
            canonical = str(d.resolve())
            if canonical in seen:
                continue
            has_concepts = any(d.rglob("concepts_import.json")) or any(d.rglob("concept_sets_import.json"))
            if has_concepts:
                seen.add(canonical)
                try:
                    steps = scan_folder(d)
                    discovered.append({
                        "name": d.name,
                        "path": str(d),
                        "folders_count": len(steps),
                        "concepts_count": sum(len(s["concepts"]) for s in steps),
                        "sets_count": sum(len(s["concept_sets"]) for s in steps),
                    })
                except Exception:
                    pass
    return discovered


def scan_folder(program_dir: Path) -> list[dict]:
    """Bottom-up post-order tree walk.
    Recursively visits every subfolder inside the selected folder regardless of depth level,
    ensuring child folders (e.g. sections) are processed in order before their parent (stage),
    branch by branch.
    """
    root = Path(program_dir)
    plan = []

    def visit(folder: Path):
        try:
            subfolders = sorted([p for p in folder.iterdir() if p.is_dir() and not p.name.startswith(".")])
        except Exception:
            subfolders = []

        for sub in subfolders:
            visit(sub)

        # Look for concepts file
        concepts = []
        for c_cand in ["concepts_import.json", "concepts.json", "concepts_export.json"]:
            cp = folder / c_cand
            if cp.is_file() and cp.stat().st_size > 0:
                try:
                    loaded = json.loads(cp.read_text(encoding="utf-8"))
                    if isinstance(loaded, list):
                        concepts = loaded
                        break
                except Exception:
                    pass

        # Look for concept sets file
        sets_ = []
        for s_cand in ["concept_sets_import.json", "concept_sets.json", "concept_sets_export.json"]:
            sp = folder / s_cand
            if sp.is_file() and sp.stat().st_size > 0:
                try:
                    loaded = json.loads(sp.read_text(encoding="utf-8"))
                    if isinstance(loaded, list):
                        sets_ = loaded
                        break
                except Exception:
                    pass

        if concepts or sets_:
            try:
                rel_path = str(folder.relative_to(root))
                if rel_path == ".":
                    rel_path = folder.name
            except Exception:
                rel_path = folder.name

            plan.append({
                "dir": folder,
                "path": folder,
                "rel_path": rel_path,
                "concepts": concepts,
                "concept_sets": sets_,
            })

    visit(root)
    return plan


def run_bulk_folder_import(
    client: OpenMRSClient,
    program_dir: str | Path,
    dry_run: bool = True,
    auto_create_classes: bool = True,
    log_fn: Optional[Callable[[str], None]] = None,
    progress_fn: Optional[Callable[[int, int, str], None]] = None,
    is_canceled_fn: Optional[Callable[[], bool]] = None,
    out_report_path: Optional[str | Path] = None,
) -> dict:
    log = log_fn or (lambda msg: None)
    prog = progress_fn or (lambda cur, tot, msg: None)
    is_canceled = is_canceled_fn or (lambda: False)

    pdir = Path(program_dir)
    steps = scan_folder(pdir)
    if not steps:
        log("No valid concept JSON folders found to import.")
        return {
            "status": "empty",
            "folders_count": 0,
            "created": 0,
            "reused": 0,
            "failed": 0,
        }

    log(f"Found {len(steps)} folder step(s) for bottom-up bulk import.")

    # Global class map
    class_map: dict[str, str] = {}
    try:
        existing_classes = client.get_concept_classes()
        for step in steps:
            for item in step["concepts"] + step["concept_sets"]:
                cls = item.get("concept_class")
                if cls and cls not in class_map:
                    if cls.strip().lower() in existing_classes:
                        class_map[cls] = cls
                    elif auto_create_classes and not dry_run:
                        try:
                            client.create_concept_class(cls)
                            class_map[cls] = cls
                            log(f"Created missing class: {cls}")
                        except Exception as e:
                            log(f"Class creation warning {cls}: {error_detail(e)}")
                            class_map[cls] = cls
                    else:
                        class_map[cls] = cls
    except Exception as e:
        log(f"Class discovery error: {error_detail(e)}")

    name_cache: dict[str, Optional[str]] = {}

    def resolve_name(name: str) -> Optional[str]:
        k = name.strip().lower()
        if k in name_cache:
            return name_cache[k]
        try:
            val = client.find_concept_by_name(name)
        except Exception as e:
            if dry_run:
                val = None
            else:
                raise
        name_cache[k] = val
        return val

    prefix = "[DRY RUN] " if dry_run else ""
    results = []
    created, reused, failed, ambiguous = 0, 0, 0, 0

    total_items = sum(len(s["concepts"]) + len(s["concept_sets"]) for s in steps)
    processed = 0

    for step_info in steps:
        if is_canceled():
            log("Bulk import stopped by user.")
            break

        rel_name = step_info["rel_path"]
        log(f"\n{prefix}=== Importing folder: {rel_name} ===")

        # Step 1: Base concepts
        for c in step_info["concepts"]:
            if is_canceled():
                break
            processed += 1
            name = extract_concept_name(c)
            if not name:
                continue
            prog(processed, total_items, f"[{rel_name}] {name}")
            raw_cls = c.get("concept_class") or c.get("conceptClass") or ""
            resolved_cls = class_map.get(raw_cls, raw_cls)

            existing = resolve_name(name)
            if existing == "AMBIGUOUS":
                ambiguous += 1
                log(f"{prefix}AMBIGUOUS: '{name}' on server - skipping")
                results.append(
                    {
                        "folder": rel_name,
                        "type": "concept",
                        "name": name,
                        "status": "AMBIGUOUS",
                        "detail": "multiple matches",
                    }
                )
                continue
            if existing:
                reused += 1
                log(f"{prefix}EXISTS: '{name}' (uuid={existing}) - reusing")
                results.append(
                    {
                        "folder": rel_name,
                        "type": "concept",
                        "name": name,
                        "status": "REUSED",
                        "detail": existing,
                    }
                )
                continue

            if dry_run:
                log(f"{prefix}Would create concept '{name}'")
                name_cache[name.strip().lower()] = "DRY-RUN-PLACEHOLDER"
                created += 1
                results.append(
                    {
                        "folder": rel_name,
                        "type": "concept",
                        "name": name,
                        "status": "WOULD_CREATE",
                        "detail": "",
                    }
                )
                continue

            try:
                res = client.create_concept(c, resolved_cls)
                new_uuid = res["uuid"]
                name_cache[name.strip().lower()] = new_uuid
                created += 1
                log(f"{prefix}CREATED: '{name}' -> {new_uuid}")
                results.append(
                    {
                        "folder": rel_name,
                        "type": "concept",
                        "name": name,
                        "status": "CREATED",
                        "detail": new_uuid,
                    }
                )
            except Exception as e:
                failed += 1
                d = error_detail(e)
                log(f"{prefix}FAILED: '{name}' - {d}")
                results.append(
                    {
                        "folder": rel_name,
                        "type": "concept",
                        "name": name,
                        "status": "FAILED",
                        "detail": d,
                    }
                )

        # Step 2: Coded answers
        if not is_canceled() and not dry_run:
            for c in step_info["concepts"]:
                if (
                    c.get("datatype", "").strip().lower() in CODED_DATATYPES
                    and c.get("answers")
                ):
                    c_name = extract_concept_name(c)
                    if not c_name:
                        continue
                    c_uuid = name_cache.get(c_name.strip().lower())
                    if (
                        c_uuid
                        and c_uuid not in ("AMBIGUOUS", "DRY-RUN-PLACEHOLDER")
                    ):
                        ans_uuids = [
                            resolve_name(a)
                            for a in c["answers"]
                            if resolve_name(a)
                            and resolve_name(a)
                            not in ("AMBIGUOUS", "DRY-RUN-PLACEHOLDER")
                        ]
                        if ans_uuids:
                            try:
                                client.set_answers(c_uuid, ans_uuids)
                            except Exception as e:
                                log(
                                    f"Failed setting answers on '{c_name}': {error_detail(e)}"
                                )

        # Step 3: Concept sets in this folder
        for s in step_info["concept_sets"]:
            if is_canceled():
                break
            processed += 1
            s_name = extract_concept_name(s)
            if not s_name:
                continue
            prog(processed, total_items, f"[{rel_name} SET] {s_name}")
            raw_cls = s.get("concept_class") or s.get("conceptClass") or "ConvSet"
            resolved_cls = class_map.get(raw_cls, raw_cls)

            set_uuid = resolve_name(s_name)
            if not set_uuid or set_uuid == "DRY-RUN-PLACEHOLDER":
                if dry_run:
                    log(f"{prefix}Would create concept set '{s_name}' (class='{resolved_cls}')")
                    name_cache[s_name.strip().lower()] = "DRY-RUN-PLACEHOLDER"
                    created += 1
                    results.append(
                        {
                            "folder": rel_name,
                            "type": "concept_set",
                            "name": s_name,
                            "status": "WOULD_CREATE",
                            "detail": "",
                        }
                    )
                else:
                    try:
                        s_entry = dict(s)
                        s_entry["datatype"] = "N/A"
                        res = client.create_concept(s_entry, resolved_cls)
                        set_uuid = res["uuid"]
                        name_cache[s_name.strip().lower()] = set_uuid
                        created += 1
                        log(f"{prefix}CREATED SET: '{s_name}' -> {set_uuid}")
                        results.append(
                            {
                                "folder": rel_name,
                                "type": "concept_set",
                                "name": s_name,
                                "status": "CREATED",
                                "detail": set_uuid,
                            }
                        )
                    except Exception as e:
                        failed += 1
                        d = error_detail(e)
                        log(f"{prefix}FAILED SET: '{s_name}' - {d}")
                        results.append(
                            {
                                "folder": rel_name,
                                "type": "concept_set",
                                "name": s_name,
                                "status": "FAILED",
                                "detail": d,
                            }
                        )
                        continue

            if s.get("members"):
                mem_list = s["members"]
                if dry_run:
                    sample = ", ".join(mem_list[:5]) + ("..." if len(mem_list) > 5 else "")
                    log(f"{prefix}Would link {len(mem_list)} member(s) to set '{s_name}': {sample}")
                elif set_uuid:
                    mem_uuids = [
                        resolve_name(m)
                        for m in mem_list
                        if resolve_name(m)
                        and resolve_name(m) not in ("AMBIGUOUS", "DRY-RUN-PLACEHOLDER")
                    ]
                    if mem_uuids:
                        try:
                            client.set_members(set_uuid, mem_uuids)
                            log(f"  Linked {len(mem_uuids)} members to set '{s_name}'")
                        except Exception as e:
                            log(
                                f"  Failed linking members to set '{s_name}': {error_detail(e)}"
                            )

    if out_report_path and results:
        rp = Path(out_report_path)
        rp.parent.mkdir(parents=True, exist_ok=True)
        with open(rp, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(
                f, fieldnames=["folder", "type", "name", "status", "detail"]
            )
            writer.writeheader()
            writer.writerows(results)

    return {
        "status": "completed",
        "folders_count": len(steps),
        "created": created,
        "reused": reused,
        "failed": failed,
        "ambiguous": ambiguous,
        "total_items": total_items,
        "results": results,
    }
